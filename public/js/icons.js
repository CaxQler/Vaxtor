/** Return a full inline <svg> string for an icon name. */
function ico(name, size) {
  const body = ICONS[name] || ICONS.box;
  const s = size || 16;
  return `<svg class="i" width="${s}" height="${s}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

window.ico = ico;
window.ICONS = ICONS;

/** Auto-fill any <span data-ico="name"> placeholders once the DOM is ready. */
function bootIcons() {
  document.querySelectorAll("[data-ico]").forEach((el) => {
    if (el.dataset.icoDone) return;
    el.innerHTML = ico(el.dataset.ico, Number(el.dataset.icoSize) || 16) + (el.textContent.trim() ? " " + el.textContent : "");
    el.dataset.icoDone = "1";
  });
}
if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", bootIcons);
else bootIcons();
window.bootIcons = bootIcons;
